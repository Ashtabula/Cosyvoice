ROOT=Path(__file__).resolve().parents[3]
EXP=Path(__file__).parent

def sha(path):
    h=hashlib.sha256()
    for f in sorted(path.rglob('*')) if path.is_dir() else [path]:
        if f.is_file():
            if path.is_dir():h.update(str(f.relative_to(path)).encode())
            with f.open('rb') as stream:
                for b in iter(lambda:stream.read(8*1024*1024),b''):h.update(b)
    return h.hexdigest()

def main():
    p=argparse.ArgumentParser();p.add_argument('--family',type=Path,required=True);a=p.parse_args()
    family=a.family;receipt=json.loads((family/'receipt.json').read_text())
    if receipt.get('status')!='PASS_FULL_RANGE_SYMBOLIC_FAMILY_EXPORT_NOT_PROMOTED':
        raise RuntimeError(f'family not accepted for staging: {receipt.get("status")}')
    if receipt.get('NBounds')!=[3,479]:raise RuntimeError(f'unexpected bounds: {receipt.get("NBounds")}')

    dest=EXP/'DeviceProbe/GeneratedAssets/acoustic'
    dest.mkdir(parents=True,exist_ok=False)
    identity={'schemaVersion':2,'sourceCommit':subprocess.check_output(['git','-C',str(ROOT),'rev-parse','HEAD'],text=True).strip(),
              'familyReceiptSha256':sha(family/'receipt.json'),'productionPromotion':False,
              'supportedNBounds':[3,479],'checkpoints':receipt['checkpoints'],
              'generationContract':receipt['generationContract'],
              'globalAcousticEnvelopeUpper':479,
              'referenceAwarePerRequestCap':True,
              'shapeSweepInputs':'zero target speech tokens + fixed validated prompt/reference conditioning + zero Flow initial state + zero HiFT excitation',
              'models':{},'base':{}}

    roles=[('conditions',family/'conditions/conditions.mlpackage')]
    roles += [(f'flow-{i}',family/f'packages/shard-{i:02d}/flow-shard.mlpackage') for i in range(6)]
    roles += [('hift',family/'hift/hift-dynamic-body-fp32.mlpackage')]
    for role,source in roles:
        if not source.exists():raise RuntimeError(f'missing {role}: {source}')
        target=dest/f'{role}.mlpackage';shutil.copytree(source,target)
        identity['models'][role]=sha(target)

    f0source=ROOT/'ios/.work/production-clean-room/fetched-runtime/f0-double'
    if not f0source.is_dir():raise RuntimeError(f'missing f0-double: {f0source}')
    shutil.copytree(f0source,dest/'f0-double');identity['models']['f0-double']=sha(dest/'f0-double')

